import {test} from 'node:test';
import assert from 'node:assert/strict';
import {createHash,generateKeyPairSync,randomUUID,sign} from 'node:crypto';
import {execFileSync,spawn} from 'node:child_process';
import {once} from 'node:events';
import {fileURLToPath} from 'node:url';
import {mkdtemp,readFile,rm,writeFile} from 'node:fs/promises';
import {tmpdir} from 'node:os';
import {join} from 'node:path';
import {createSyntheticWorkspace,sealSyntheticWorkspace,bindDynamicSyntheticWorkspace,sealDynamicSyntheticWorkspace,bindUploadedWorkspace,sealUploadedWorkspace} from '../scripts/synthetic-seal-orchestration.ts';
import {createSyntheticFixture} from '../scripts/synthetic-seal-fixture.ts';
import {verifySyntheticSeal,verifyDynamicSyntheticSeal,verifyUploadedSeal} from '../scripts/synthetic-seal-verify.ts';
const run=(args:string[],cwd:string)=>execFileSync('openssl',args,{cwd,stdio:'pipe'});
test('fixture-only seal persists each step, resumes, verifies and rejects tampering',async()=>{
 const temp=await mkdtemp(join(tmpdir(),'esign-adapter-test-'));let workspace='',race='',dynamicWorkspace='',uploadedWorkspace='',largeWorkspace='';
 try {
  run(['req','-x509','-newkey','rsa:2048','-nodes','-keyout','root.key','-out','root.pem','-subj','/CN=Synthetic Root','-days','2','-addext','basicConstraints=critical,CA:TRUE','-addext','keyUsage=critical,keyCertSign,cRLSign'],temp);
  run(['req','-newkey','rsa:2048','-nodes','-keyout','tsa.key','-out','tsa.csr','-subj','/CN=Synthetic TSA'],temp);
  await writeFile(join(temp,'ext'),'basicConstraints=critical,CA:FALSE\nkeyUsage=critical,digitalSignature\nextendedKeyUsage=critical,timeStamping\n');
  run(['x509','-req','-in','tsa.csr','-CA','root.pem','-CAkey','root.key','-set_serial','1','-days','1','-extfile','ext','-out','tsa.pem'],temp);
  await writeFile(join(temp,'serial'),'01\n');await writeFile(join(temp,'tsa.cnf'),'[tsa]\ndefault_tsa=server\n[server]\nserial=serial\nsigner_cert=tsa.pem\nsigner_key=tsa.key\nsigner_digest=sha256\ndefault_policy=1.2.3.4\ndigests=sha256\n');
  const roots=await readFile(join(temp,'root.pem')),pair=generateKeyPairSync('ec',{namedCurve:'prime256v1'}),spki=pair.publicKey.export({type:'spki',format:'der'}),fingerprint=createHash('sha256').update(spki).digest('hex');
  let signs=0,timestamps=0;
  const deps={roots,aws:async(args:string[],message?:Buffer)=>{
   if(args[0]==='get-public-key') return {KeyId:'fixture-key',KeySpec:'ECC_NIST_P256',KeyUsage:'SIGN_VERIFY',SigningAlgorithms:['ECDSA_SHA_256'],PublicKey:spki.toString('base64')};
   signs++;assert.ok(message);assert.equal(args[args.indexOf('--key-id')+1],'alias/esign-local-test-signing');assert.equal(args[args.indexOf('--message-type')+1],'DIGEST');
   assert.deepEqual(await readFile(args[args.indexOf('--message')+1].replace('fileb://','')),createHash('sha256').update(message).digest());
   return {KeyId:'fixture-key',SigningAlgorithm:'ECDSA_SHA_256',Signature:sign('sha256',message,pair.privateKey).toString('base64')};
  },timestamp:async(request:Buffer)=>{timestamps++;const suffix=randomUUID(),query=`request-${suffix}`,reply=`response-${suffix}`;await writeFile(join(temp,query),request);run(['ts','-reply','-config','tsa.cnf','-queryfile',query,'-out',reply],temp);return readFile(join(temp,reply));}};
  workspace=await createSyntheticWorkspace();
  await writeFile(join(temp,'kms-private.pem'),pair.privateKey.export({type:'pkcs8',format:'pem'}));
  const helper=fileURLToPath(new URL('./helpers/seal-crash-child.ts',import.meta.url));
  const child=spawn(process.execPath,[helper,workspace,temp],{stdio:['ignore','pipe','pipe']});
  const chunk=await Promise.race([once(child.stdout,'data').then(x=>x[0]),once(child,'exit').then(()=>{throw new Error('child exited before timestamp');})]);
  assert.match(chunk.toString(),/timestamp-ready/);child.kill('SIGKILL');const [,signal]=await once(child,'exit');assert.equal(signal,'SIGKILL');
  const before=await readFile(join(workspace,'signature'));
  await sealSyntheticWorkspace(workspace,deps);
  assert.deepEqual(await readFile(join(workspace,'signature')),before);
  await verifySyntheticSeal(workspace,fingerprint,roots);
  const dynamic=await verifyDynamicSyntheticSeal(workspace,fingerprint,roots);
  assert.equal(dynamic.envelopeId,JSON.parse((await readFile(join(workspace,'manifest'))).toString()).envelopeId);
  await assert.rejects(verifyDynamicSyntheticSeal(workspace,'0'.repeat(64),roots));
  await sealSyntheticWorkspace(workspace,deps);
  assert.equal(signs,0);assert.equal(timestamps,1);
  await writeFile(join(workspace,'d3'),'tampered');
  await assert.rejects(verifyDynamicSyntheticSeal(workspace,fingerprint,roots));
  await assert.rejects(sealSyntheticWorkspace(workspace,deps));
  assert.equal(signs,0);assert.equal(timestamps,1);
  await assert.rejects(sealSyntheticWorkspace(temp,deps));
  race=await createSyntheticWorkspace();
  await Promise.all([sealSyntheticWorkspace(race,deps),sealSyntheticWorkspace(race,deps)]);
  await verifySyntheticSeal(race,fingerprint,roots);
  const fixture=await createSyntheticFixture();
  const binding=await mkdtemp(join(tmpdir(),'esign-binding-test-'));
  const winners=await Promise.all([bindDynamicSyntheticWorkspace(binding,fixture),bindDynamicSyntheticWorkspace(binding,fixture)]);
  assert.equal(winners[0],winners[1]);dynamicWorkspace=winners[0];
  assert.equal(await bindDynamicSyntheticWorkspace(binding,fixture),dynamicWorkspace);
  const altered={...fixture,envelopeId:'different'};
  await assert.rejects(bindDynamicSyntheticWorkspace(binding,altered));
  const interrupted=spawn(process.execPath,[helper,dynamicWorkspace,temp,'dynamic'],{stdio:['ignore','pipe','pipe']});
  const ready=await Promise.race([once(interrupted.stdout,'data').then(x=>x[0]),once(interrupted,'exit').then(()=>{throw new Error('dynamic child exited before timestamp');})]);
  assert.match(ready.toString(),/timestamp-ready/);interrupted.kill('SIGKILL');assert.equal((await once(interrupted,'exit'))[1],'SIGKILL');
  const retained=await readFile(join(dynamicWorkspace,'signature')),signsBefore=signs;
  await Promise.all([sealDynamicSyntheticWorkspace(dynamicWorkspace,fixture,deps),sealDynamicSyntheticWorkspace(dynamicWorkspace,fixture,deps)]);
  assert.deepEqual(await readFile(join(dynamicWorkspace,'signature')),retained);assert.equal(signs,signsBefore);
  assert.equal((await verifyDynamicSyntheticSeal(dynamicWorkspace,fingerprint,roots)).envelopeId,fixture.envelopeId);
  const verifier=fileURLToPath(new URL('../scripts/synthetic-seal-dynamic-verify.ts',import.meta.url));
  const output=execFileSync(process.execPath,[verifier,dynamicWorkspace,fingerprint,join(temp,'root.pem')],{encoding:'utf8'});
  assert.equal(JSON.parse(output).envelopeId,fixture.envelopeId);
  assert.throws(()=>execFileSync(process.execPath,[verifier,dynamicWorkspace,'0'.repeat(64),join(temp,'root.pem')],{stdio:'pipe'}));
  await assert.rejects(verifySyntheticSeal(dynamicWorkspace,fingerprint,roots));
  await sealDynamicSyntheticWorkspace(dynamicWorkspace,fixture,deps);
  const uploadBinding=await mkdtemp(join(tmpdir(),'esign-upload-binding-test-'));
  uploadedWorkspace=await bindUploadedWorkspace(uploadBinding,fixture);
  assert.equal(await bindUploadedWorkspace(uploadBinding,fixture),uploadedWorkspace);
  await assert.rejects(bindUploadedWorkspace(uploadBinding,{...fixture,envelopeId:'other'}));
  await sealUploadedWorkspace(uploadedWorkspace,fixture,deps);
  const uploadResult=await verifyUploadedSeal(uploadedWorkspace,fingerprint,roots);
  assert.equal(uploadResult.envelopeId,fixture.envelopeId);
  const uploadVerifier=fileURLToPath(new URL('../scripts/upload-seal-verify.ts',import.meta.url));
  assert.equal(JSON.parse(execFileSync(process.execPath,[uploadVerifier,uploadedWorkspace,fingerprint,join(temp,'root.pem')],{encoding:'utf8'})).envelopeId,fixture.envelopeId);
  assert.throws(()=>execFileSync(process.execPath,[uploadVerifier,uploadedWorkspace,'0'.repeat(64),join(temp,'root.pem')],{stdio:'pipe'}));
  await assert.rejects(verifyDynamicSyntheticSeal(uploadedWorkspace,fingerprint,roots));
  const signature=await readFile(join(uploadedWorkspace,'signature'));
  await sealUploadedWorkspace(uploadedWorkspace,fixture,deps);
  assert.deepEqual(await readFile(join(uploadedWorkspace,'signature')),signature);
  const largeBinding=await mkdtemp(join(tmpdir(),'esign-large-binding-test-'));
  const large={...fixture,artifacts:fixture.artifacts.map((bytes:Uint8Array,i:number)=>i===3?Buffer.concat([Buffer.from(bytes),Buffer.alloc(1024*1024)]):bytes)};
  largeWorkspace=await bindUploadedWorkspace(largeBinding,large);await sealUploadedWorkspace(largeWorkspace,large,deps);
  assert.equal((await verifyUploadedSeal(largeWorkspace,fingerprint,roots)).envelopeId,fixture.envelopeId);
  await assert.rejects(bindUploadedWorkspace(largeBinding,{...large,artifacts:large.artifacts.map((b:Uint8Array,i:number)=>i===3?new Uint8Array(8*1024*1024+1):b)}));
  await rm(largeBinding,{recursive:true,force:true});
  await rm(uploadBinding,{recursive:true,force:true});
  await rm(binding,{recursive:true,force:true});
 } finally {await rm(temp,{recursive:true,force:true});if(workspace) await rm(workspace,{recursive:true,force:true});if(race) await rm(race,{recursive:true,force:true});if(dynamicWorkspace) await rm(dynamicWorkspace,{recursive:true,force:true});if(uploadedWorkspace) await rm(uploadedWorkspace,{recursive:true,force:true});if(largeWorkspace) await rm(largeWorkspace,{recursive:true,force:true});}
});
