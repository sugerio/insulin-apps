import {unstable_splitSqlQuery} from 'wrangler';
import { test } from 'node:test';
import assert from 'node:assert/strict';
import { readFile, readdir } from 'node:fs/promises';
import { Miniflare } from 'miniflare';
import { PDFDocument } from 'pdf-lib';
import app from '../src/worker.ts';

test('migration preserves and identifies a pre-snapshot pending signature without inventing its layout', async () => {
  const mf = new Miniflare({modules:true,script:'export default {fetch(){return new Response("ok")}}',d1Databases:['DB'],r2Buckets:['ARTIFACTS','TEST_MAIL']});
  try {
    const db=await mf.getD1Database('DB'),bucket=await mf.getR2Bucket('ARTIFACTS'),mail=await mf.getR2Bucket('TEST_MAIL');
    const migrate=async(name:string)=>{const sql=await readFile(new URL(`../migrations/${name}`,import.meta.url),'utf8');await db.batch(unstable_splitSqlQuery(sql).map(s=>db.prepare(s)));};
    for(const name of (await readdir(new URL('../migrations/',import.meta.url))).filter(n=>n.endsWith('.sql') && n<'0012').sort()) await migrate(name);
    const pdf=await PDFDocument.create();pdf.addPage();pdf.addPage();const bytes=await pdf.save();
    const sha=async(bytes:Uint8Array)=>Array.from(new Uint8Array(await crypto.subtle.digest('SHA-256',Uint8Array.from(bytes))),n=>n.toString(16).padStart(2,'0')).join('');
    const inputHash=await sha(bytes),secret='test-key-0123456789-abcdefghijklmnopqrstuvwxyz',keyHash=await sha(new TextEncoder().encode(secret));
    const original=await PDFDocument.create();original.addPage();const d0=await original.save(),h0=await sha(d0);
    const event1=await sha(new TextEncoder().encode(JSON.stringify(['esign-signature-event-v1','env',1,'','s1','ana','Ana','d0',h0,1000,1001])));
    const event2=await sha(new TextEncoder().encode(JSON.stringify(['esign-signature-event-v1','env',2,event1,'s2','marcus','Marcus','d1',inputHash,2000,2001])));
    await bucket.put('d0.pdf',d0);await bucket.put('d1.pdf',bytes);
    await db.exec(`INSERT INTO tenants VALUES ('tenant');
INSERT INTO api_keys (key_hash,tenant_id) VALUES ('${keyHash}','tenant');
INSERT INTO templates VALUES ('template','tenant','source','[]',1);
INSERT INTO envelopes VALUES ('env','tenant','template','IN_PROGRESS',1);
INSERT INTO tasks VALUES ('ana','env','ana','Ana','ana@example.com',1,'SIGNED');
INSERT INTO tasks VALUES ('marcus','env','marcus','Marcus','marcus@example.com',2,'SIGNED');
INSERT INTO recipient_page_sessions VALUES ('sa','tenant','env','ana','https://host.example.com',999999);
INSERT INTO recipient_page_sessions VALUES ('sm','tenant','env','marcus','https://host.example.com',999999);
INSERT INTO artifacts VALUES ('d0','env','d0.pdf','${h0}');
INSERT INTO signature_records VALUES ('s1','env','ana',1,'sa','Ana','d0','${h0}',1000,1001);
INSERT INTO signature_records VALUES ('s2','env','marcus',2,'sm','Marcus','d1','${inputHash}',2000,2001);
INSERT INTO signature_events VALUES ('s1','env',1,'','${event1}');
INSERT INTO signature_events VALUES ('s2','env',2,'${event1}','${event2}');
INSERT INTO signature_jobs VALUES ('j1','s1','DONE');
INSERT INTO signature_jobs VALUES ('j2','s2','PENDING');
INSERT INTO signature_outputs VALUES ('j1','d1','d1.pdf','${inputHash}');
INSERT INTO signature_layouts VALUES ('j1',2,0);`);
    const tables=['signature_records','signature_events','signature_jobs','signature_outputs','signature_layouts','tasks','envelopes'];
    const snapshot=()=>Promise.all(tables.map(table=>db.prepare(`SELECT ${table==='signature_events'?'signature_id,envelope_id,sequence,previous_hash,event_hash':table==='signature_records'?'id,envelope_id,task_id,sequence,session_hash,recipient_name,input_artifact_id,input_sha256,otp_verified_at,consented_at':'*'} FROM ${table} ORDER BY rowid`).all().then(r=>r.results)));
    const before=await snapshot();
    for(const name of (await readdir(new URL('../migrations/',import.meta.url))).filter(n=>n.endsWith('.sql') && n>='0012').sort()) await migrate(name);
    assert.deepEqual((await db.prepare('SELECT otp_recipient_email FROM signature_records ORDER BY sequence').all()).results,[{otp_recipient_email:null},{otp_recipient_email:null}]);
    const env={DB:db,ARTIFACTS:bucket,TEST_MAIL:mail,LOCAL_TEST_MODE:'true',LOCAL_TEST_OTP_KEY:'local-test-pepper-at-least-32-bytes'};
    const run=()=>app.fetch(new Request('http://localhost/v1/envelopes/env/process',{method:'POST',headers:{authorization:`Bearer ${secret}`}}),env);
    const response=await run();assert.equal(response.status,409);assert.deepEqual(await response.json(),{error:'signature_input_layout_missing'});
    assert.equal((await db.prepare('SELECT count(*) AS n FROM signature_input_layouts').first())!.n,0);
    assert.deepEqual(await snapshot(),before);
    assert.deepEqual(new Uint8Array(await (await bucket.get('d1.pdf'))!.arrayBuffer()),bytes);
    assert.equal((await bucket.list()).objects.length,2);
    // Older names may not be renderable: missing-snapshot diagnosis takes precedence without writing.
    const unsupported='李雷';
    const unsupportedEvent=await sha(new TextEncoder().encode(JSON.stringify(['esign-signature-event-v1','env',2,event1,'s2','marcus',unsupported,'d1',inputHash,2000,2001])));
    await db.prepare("UPDATE signature_records SET recipient_name=? WHERE id='s2'").bind(unsupported).run();
    await db.prepare("UPDATE signature_events SET event_hash=? WHERE signature_id='s2'").bind(unsupportedEvent).run();
    await db.prepare("UPDATE tasks SET recipient_name=? WHERE id='marcus'").bind(unsupported).run();
    const unsupportedBefore=await snapshot();
    const unauthorized=await app.fetch(new Request('http://localhost/v1/envelopes/env/process',{method:'POST'}),env);
    assert.equal(unauthorized.status,401);
    const unsupportedResponse=await run();assert.equal(unsupportedResponse.status,409);assert.deepEqual(await unsupportedResponse.json(),{error:'signature_input_layout_missing'});
    assert.deepEqual(await snapshot(),unsupportedBefore);
    assert.equal((await db.prepare('SELECT count(*) AS n FROM signature_input_layouts').first())!.n,0);
    assert.deepEqual(new Uint8Array(await (await bucket.get('d1.pdf'))!.arrayBuffer()),bytes);
    assert.equal((await bucket.list()).objects.length,2);
    // A different valid slot has the same input hash and page count; neither state proves the historical slot.
    await db.prepare("UPDATE signature_layouts SET slot=1 WHERE job_id='j1'").run();
    const retry=await run();assert.equal(retry.status,409);assert.deepEqual(await retry.json(),{error:'signature_input_layout_missing'});
    assert.equal((await db.prepare('SELECT count(*) AS n FROM signature_input_layouts').first())!.n,0);
    assert.equal((await db.prepare("SELECT status FROM signature_jobs WHERE id='j2'").first())!.status,'PENDING');
  } finally {await mf.dispose();}
});
